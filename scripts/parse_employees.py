def decode_val(s):
    res = []
    for c in s:
        code = ord(c)
        if code in (9, 10, 32):
            res.append(c)
        elif 0 < code < 128:
            try:
                res.append(bytes([code + 160]).decode("cp874"))
            except Exception:
                res.append(c)
        else:
            res.append(c)
    return "".join(res)

