    parts = line.split("\t")
    if len(parts) >= 2:
        emp_id = parts[0].strip()
        raw_name = parts[1].strip()
        # sometimes name wraps onto next line if there was an embedded newline
        while (i + 1 < len(lines)) and ("\t" not in lines[i+1]) and not (len(lines[i+1].split()) > 0 and lines[i+1].split()[0].isdigit() and len(lines[i+1].split()[0]) >= 5):
            i += 1
            raw_name += " " + lines[i].strip()
        name = decode_val(raw_name)
        # clean up any excessive spaces
        name = " ".join(name.split())
        employees.append({"id": emp_id, "name": name})
