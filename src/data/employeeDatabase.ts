export function findEmployeeById(id: string): BMTAEmployee | undefined {
  const cleanId = id.trim();
  if (!cleanId) return undefined;
  const name = EMPLOYEE_ID_MAP[cleanId];
  if (name) {
    return { id: cleanId, name };
  }
  return BMTA_ZONE6_EMPLOYEES.find((e) => e.id === cleanId);
}

export function findEmployeeByName(name: string): BMTAEmployee | undefined {
  const cleanName = name.trim().toLowerCase();
  if (!cleanName) return undefined;
  return BMTA_ZONE6_EMPLOYEES.find((e) => e.name.toLowerCase().includes(cleanName));
}

export function searchEmployees(query: string, limit = 8): BMTAEmployee[] {
  const q = query.trim().toLowerCase();
  if (!q) return POPULAR_ZONE6_EMPLOYEES.slice(0, limit);
  return BMTA_ZONE6_EMPLOYEES.filter(
    (e) => e.id.toLowerCase().includes(q) || e.name.toLowerCase().includes(q)
  ).slice(0, limit);
}

